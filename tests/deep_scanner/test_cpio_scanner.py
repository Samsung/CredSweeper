class TestCpioScanner(unittest.TestCase):

    def test_match_n(self):
        # Wrong data type
        with self.assertRaises(AttributeError):
            CpioScanner.match(None)
        with self.assertRaises(AttributeError):
            CpioScanner.match(1)
        # Too short
        self.assertFalse(CpioScanner.match(b""))
        self.assertFalse(CpioScanner.match(b"07"))
        # Wrong signature
        self.assertFalse(CpioScanner.match(b"0707070707"))

    def test_match_p(self):
        # Valid cpio archive signature
        self.assertTrue(CpioScanner.match(b"0707070707\0\0"))

    def test_walk_n(self):
        with self.assertRaises(ValueError):
            list(CpioScanner.walk_cpio(b""))

    def test_walk_p(self):
        for sample in CPIO_SAMPLES:
            result = list([(name, content) for _content_offset, name, content in CpioScanner.walk_cpio(sample)])
            self.assertListEqual([('/tmp/credentials/token', b'token=4a1ce4d9-4afe-4a7e-4efa-491274c94d81'),
                                  ('/tmp/credentials/таємниця.txt',
                                   b'password="FL\xc5\xb0GG\xc3\x85\xc6\x8fNK\xe2\x88\x82\xe2\x82\xac\xc4\x8cHI'
                                   b'\xc5\x92\xce\xb2\xc3\x98L\xe2\x88\xab\xc3\x8aN"\n')], result)
